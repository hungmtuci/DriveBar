import Foundation
import AppKit
import Carbon

enum ClipboardEntryKind: String, Codable, Sendable {
    case text
    case url
    case files
    case image
}

struct ClipboardHistoryEntry: Codable, Identifiable, Equatable, Sendable {
    let id: String
    let kind: ClipboardEntryKind
    let title: String
    let textContent: String
    let filePaths: [String]
    let sourceAppName: String?
    var timestamp: Double
    let charCount: Int
    let contentHash: String
}

@MainActor
final class ClipboardHistoryService: ObservableObject {
    static let shared = ClipboardHistoryService()

    @Published private(set) var entries: [ClipboardHistoryEntry] = []

    var isTemporarilySuspended: Bool = false
    private var pollTimer: Timer?
    private var lastObservedChangeCount: Int = NSPasteboard.general.changeCount
    private var ignoredChangeCount: Int = -1
    private let maxEntries: Int = 80

    private let homePath = FileManager.default.homeDirectoryForCurrentUser.path
    private var historyFilePath: String { "\(homePath)/.config/alfred-scripts/clipboard_history.json" }
    private var imagesDirPath: String {
        "\(homePath)/Library/Application Support/DriveBar/ClipboardHistory"
    }

    private static let concealedTypeStrings: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
        "ValidOnlyAtTimeOfCopy"
    ]

    private init() {
        loadFromDiskAsync()
    }

    func start() {
        updatePollingState()
    }

    func updatePollingState() {
        pollTimer?.invalidate()
        pollTimer = nil
        guard AppSettings.shared.enableClipboardHistory else { return }

        lastObservedChangeCount = NSPasteboard.general.changeCount
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.65, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.pollPasteboardIfNeeded()
            }
        }
    }

    func noteInternalPasteboardWrite() {
        let count = NSPasteboard.general.changeCount
        ignoredChangeCount = count
        lastObservedChangeCount = count
    }

    private func pollPasteboardIfNeeded() {
        guard AppSettings.shared.enableClipboardHistory, !isTemporarilySuspended else { return }
        let pb = NSPasteboard.general
        let currentCount = pb.changeCount
        guard currentCount != lastObservedChangeCount else { return }
        lastObservedChangeCount = currentCount
        guard currentCount != ignoredChangeCount else { return }

        // Respect password managers & transient/concealed clipboard items
        let allTypes = Set((pb.types ?? []).map(\.rawValue))
        if !allTypes.isDisjoint(with: Self.concealedTypeStrings) {
            return
        }

        let frontApp = NSWorkspace.shared.frontmostApplication
        let ownPID = ProcessInfo.processInfo.processIdentifier
        let appName: String? = (frontApp?.processIdentifier == ownPID) ? nil : frontApp?.localizedName

        // 1. Copied File URLs
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            let joined = paths.joined(separator: "\n")
            let firstTitle = urls.count == 1
                ? urls[0].lastPathComponent
                : "\(urls.count) tệp/thư mục (\(urls[0].lastPathComponent)...)"
            let entry = ClipboardHistoryEntry(
                id: UUID().uuidString,
                kind: .files,
                title: firstTitle,
                textContent: joined,
                filePaths: paths,
                sourceAppName: appName ?? "Finder",
                timestamp: Date().timeIntervalSince1970,
                charCount: joined.count,
                contentHash: "files:\(joined)"
            )
            insertOrPromote(entry)
            return
        }

        // 2. Copied Plain Text / URL / Markdown / Code
        if let rawText = pb.string(forType: .string) {
            let trimmed = rawText.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty {
                // Cap huge multi-MB copies at 250k chars so RAM stays tiny
                let capped = rawText.count > 250_000 ? String(rawText.prefix(250_000)) : rawText
                let isWebURL: Bool = {
                    guard !trimmed.contains("\n"), !trimmed.contains(" "),
                          let u = URL(string: trimmed),
                          let scheme = u.scheme?.lowercased() else { return false }
                    return scheme == "http" || scheme == "https"
                }()

                let singleLineTitle = trimmed
                    .components(separatedBy: .newlines)
                    .map { $0.trimmingCharacters(in: .whitespaces) }
                    .first(where: { !$0.isEmpty }) ?? trimmed
                let displayTitle = singleLineTitle.count > 92
                    ? String(singleLineTitle.prefix(92)) + "…"
                    : singleLineTitle

                let entry = ClipboardHistoryEntry(
                    id: UUID().uuidString,
                    kind: isWebURL ? .url : .text,
                    title: displayTitle,
                    textContent: capped,
                    filePaths: [],
                    sourceAppName: appName,
                    timestamp: Date().timeIntervalSince1970,
                    charCount: rawText.count,
                    contentHash: "txt:\(capped.hashValue):\(capped.count)"
                )
                insertOrPromote(entry)
                return
            }
        }

        // 3. Copied Screenshot / Image in Clipboard (e.g. ⌘⌃⇧4)
        if let pngOrTiffData = pb.data(forType: .png) ?? pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: pngOrTiffData),
           rep.pixelsWide >= 8 && rep.pixelsHigh >= 8,
           let pngData = rep.representation(using: .png, properties: [:]) {
            let hashKey = "img:\(rep.pixelsWide)x\(rep.pixelsHigh):\(pngData.count)"
            if let existingIdx = entries.firstIndex(where: { $0.contentHash == hashKey }) {
                var existing = entries.remove(at: existingIdx)
                existing.timestamp = Date().timeIntervalSince1970
                entries.insert(existing, at: 0)
                persistAsync()
                return
            }

            let id = UUID().uuidString
            let dir = imagesDirPath
            let filePath = "\(dir)/Clip_\(id.prefix(8)).png"
            let w = rep.pixelsWide
            let h = rep.pixelsHigh
            let byteStr = ByteCountFormatter.string(fromByteCount: Int64(pngData.count), countStyle: .file)

            Task.detached(priority: .utility) {
                try? FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
                try? pngData.write(to: URL(fileURLWithPath: filePath), options: .atomic)
                let entry = ClipboardHistoryEntry(
                    id: id,
                    kind: .image,
                    title: "Ảnh chụp màn hình / Hình ảnh (\(w)×\(h) • \(byteStr))",
                    textContent: "Hình ảnh Clipboard \(w)x\(h)",
                    filePaths: [filePath],
                    sourceAppName: appName ?? "Screenshot",
                    timestamp: Date().timeIntervalSince1970,
                    charCount: pngData.count,
                    contentHash: hashKey
                )
                await MainActor.run {
                    ClipboardHistoryService.shared.insertOrPromote(entry)
                }
            }
        }
    }

    /// Quick zero-I/O check whether the current pasteboard or recent history holds an image for instant OCR.
    var hasClipboardImageAvailable: Bool {
        let pb = NSPasteboard.general
        if let types = pb.types, (types.contains(.png) || types.contains(.tiff)) {
            return true
        }
        return entries.contains { $0.kind == .image }
    }

    /// Ensures the current image on `NSPasteboard.general` (or latest image in history) is saved as a local PNG URL
    /// for instant Apple Vision OCR or Universal Actions.
    func materializeCurrentClipboardImageURL() -> URL? {
        let pb = NSPasteboard.general
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let first = urls.first {
            let ext = first.pathExtension.lowercased()
            if ["png", "jpg", "jpeg", "heic", "webp", "tiff", "tif", "bmp", "gif"].contains(ext),
               FileManager.default.fileExists(atPath: first.path) {
                return first
            }
        }

        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: data),
           let png = rep.representation(using: .png, properties: [:]) {
            let dir = imagesDirPath
            try? FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
            let df = DateFormatter()
            df.dateFormat = "yyyyMMdd_HHmmss"
            let path = "\(dir)/OCR_Clipboard_\(df.string(from: Date())).png"
            let url = URL(fileURLWithPath: path)
            if (try? png.write(to: url, options: .atomic)) != nil {
                return url
            }
        }

        if let latestImg = entries.first(where: { $0.kind == .image }),
           let firstPath = latestImg.filePaths.first,
           FileManager.default.fileExists(atPath: firstPath) {
            return URL(fileURLWithPath: firstPath)
        }
        return nil
    }

    private func insertOrPromote(_ newEntry: ClipboardHistoryEntry) {
        if let idx = entries.firstIndex(where: { $0.contentHash == newEntry.contentHash }) {
            var promoted = entries.remove(at: idx)
            promoted.timestamp = newEntry.timestamp
            entries.insert(promoted, at: 0)
        } else {
            entries.insert(newEntry, at: 0)
        }

        if entries.count > maxEntries {
            let removed = entries.suffix(from: maxEntries)
            let orphanImages = removed.filter { $0.kind == .image }.flatMap(\.filePaths)
            entries = Array(entries.prefix(maxEntries))
            if !orphanImages.isEmpty {
                Task.detached(priority: .background) {
                    for p in orphanImages {
                        try? FileManager.default.removeItem(atPath: p)
                    }
                }
            }
        }

        persistAsync()
    }

    func clearHistory() {
        let imgDir = imagesDirPath
        let histFile = historyFilePath
        entries.removeAll()
        Task.detached(priority: .utility) {
            try? FileManager.default.removeItem(atPath: histFile)
            try? FileManager.default.removeItem(atPath: imgDir)
        }
    }

    func entry(withID id: String) -> ClipboardHistoryEntry? {
        entries.first { $0.id == id }
    }

    func previewURLs(for entry: ClipboardHistoryEntry) -> [URL] {
        switch entry.kind {
        case .files, .image:
            return entry.filePaths
                .filter { $0.contains("/Library/CloudStorage/") || FileManager.default.fileExists(atPath: $0) }
                .map { URL(fileURLWithPath: $0) }
        case .text, .url:
            let previewPath = (NSTemporaryDirectory() as NSString).appendingPathComponent("DriveBar_ClipPreview.txt")
            let url = URL(fileURLWithPath: previewPath)
            try? entry.textContent.write(to: url, atomically: true, encoding: .utf8)
            return [url]
        }
    }

    // MARK: - Search & Build Result Items (`c` / `c + từ khóa`)

    func searchResultItems(query: String, limit: Int = 50) -> [SearchResultItem] {
        let qNorm = GoogleDriveIndexService.removeAccents(query)
            .lowercased()
            .trimmingCharacters(in: .whitespacesAndNewlines)
        let tokens = qNorm.split(separator: " ").map(String.init).filter { !$0.isEmpty }

        let filtered: [ClipboardHistoryEntry]
        if tokens.isEmpty {
            filtered = Array(entries.prefix(limit))
        } else {
            filtered = entries.filter { item in
                let hay = GoogleDriveIndexService.removeAccents(
                    "\(item.title) \(item.textContent) \(item.sourceAppName ?? "") \(item.kind.rawValue)"
                ).lowercased()
                return tokens.allSatisfy { hay.contains($0) }
            }
        }

        if filtered.isEmpty {
            return [
                SearchResultItem(
                    id: "clip:empty",
                    title: entries.isEmpty
                        ? "Lịch sử Clipboard hiện đang trống"
                        : "Không tìm thấy mục Clipboard nào khớp '\(query)'",
                    subtitle: "Sao chép văn bản, liên kết, tệp tin hoặc chụp ảnh màn hình (⌘⌃⇧4) để DriveBar lưu tự động",
                    path: nil,
                    isDirectory: false,
                    kind: .infoBanner,
                    badge: "Clipboard",
                    sfSymbolFallback: "doc.on.clipboard"
                )
            ]
        }

        let relFormatter = RelativeDateTimeFormatter()
        relFormatter.locale = Locale(identifier: "vi_VN")
        relFormatter.unitsStyle = .abbreviated
        let now = Date()

        return filtered.prefix(limit).map { entry in
            let relTime = relFormatter.localizedString(for: Date(timeIntervalSince1970: entry.timestamp), relativeTo: now)
            var subParts: [String] = [relTime]
            if let app = entry.sourceAppName, !app.isEmpty {
                subParts.append(app)
            }
            let badgeText: String
            let fallbackSym: String
            let itemPath: String?

            switch entry.kind {
            case .text:
                let lineCount = max(1, entry.textContent.components(separatedBy: .newlines).count)
                subParts.append("\(entry.charCount.formatted()) ký tự" + (lineCount > 1 ? " • \(lineCount) dòng" : ""))
                subParts.append("↩ Dán ngay • ⌥↩ Chỉ Copy • ⇧ Quick Look")
                badgeText = "Văn bản"
                fallbackSym = "doc.on.clipboard"
                itemPath = nil

            case .url:
                subParts.append("↩ Dán ngay • ⌘↩ Mở trình duyệt • ⇥ Convert sang .MD")
                badgeText = "URL"
                fallbackSym = "link"
                itemPath = nil

            case .files:
                subParts.append("↩ Dán tệp • ⌘↩ Hiện Finder • ⇥ Universal Actions")
                badgeText = entry.filePaths.count > 1 ? "\(entry.filePaths.count) tệp" : "Tệp"
                fallbackSym = "doc.on.doc"
                itemPath = entry.filePaths.first

            case .image:
                subParts.append("↩ Dán ảnh • ⇧ Quick Look • ⇥ OCR Tiếng Việt sang .MD")
                badgeText = "Hình ảnh"
                fallbackSym = "photo"
                itemPath = entry.filePaths.first
            }

            return SearchResultItem(
                id: "clip:\(entry.id)",
                title: entry.title,
                subtitle: subParts.joined(separator: " • "),
                path: itemPath,
                isDirectory: false,
                kind: .clipboardItem(id: entry.id),
                badge: badgeText,
                sfSymbolFallback: fallbackSym
            )
        }
    }

    // MARK: - Restore to Pasteboard & Auto-Paste into Previous Frontmost App

    func activateEntry(
        _ entry: ClipboardHistoryEntry,
        autoPaste: Bool,
        previousApp: NSRunningApplication?
    ) {
        let pb = NSPasteboard.general
        pb.clearContents()

        switch entry.kind {
        case .text, .url:
            pb.setString(entry.textContent, forType: .string)

        case .files:
            let validURLs = entry.filePaths
                .filter { $0.contains("/Library/CloudStorage/") || FileManager.default.fileExists(atPath: $0) }
                .map { URL(fileURLWithPath: $0) as NSURL }
            if !validURLs.isEmpty {
                pb.writeObjects(validURLs)
            } else {
                pb.setString(entry.textContent, forType: .string)
            }

        case .image:
            if let imgPath = entry.filePaths.first,
               let nsImg = NSImage(contentsOfFile: imgPath) {
                pb.writeObjects([nsImg])
            }
        }

        noteInternalPasteboardWrite()

        // Promote entry timestamp to top
        if let idx = entries.firstIndex(where: { $0.id == entry.id }) {
            var moved = entries.remove(at: idx)
            moved.timestamp = Date().timeIntervalSince1970
            entries.insert(moved, at: 0)
            persistAsync()
        }

        LauncherPanelController.shared.hide()

        guard autoPaste else {
            FloatingToastController.shared.showSuccess(
                title: "Đã sao chép lại vào Clipboard",
                subtitle: entry.title,
                symbol: "doc.on.clipboard"
            )
            return
        }

        if let prev = previousApp, !prev.isTerminated {
            NSApp.yieldActivation(to: prev)
            prev.activate()
        }

        if AXIsProcessTrusted() {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) {
                let src = CGEventSource(stateID: .hidSystemState)
                let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
                down?.flags = .maskCommand
                let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
                up?.flags = .maskCommand
                down?.post(tap: .cghidEventTap)
                up?.post(tap: .cghidEventTap)
            }
        } else {
            FloatingToastController.shared.showSuccess(
                title: "Đã lưu vào Clipboard (Nhấn ⌘V để dán)",
                subtitle: entry.title,
                symbol: "doc.on.clipboard"
            )
        }
    }

    // MARK: - Persistence

    private func loadFromDiskAsync() {
        let path = historyFilePath
        Task.detached(priority: .utility) {
            guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
                  let decoded = try? JSONDecoder().decode([ClipboardHistoryEntry].self, from: data) else {
                return
            }
            let valid = decoded.filter { item in
                if item.kind == .image, let p = item.filePaths.first {
                    return FileManager.default.fileExists(atPath: p)
                }
                return true
            }
            await MainActor.run {
                let svc = ClipboardHistoryService.shared
                if svc.entries.isEmpty {
                    svc.entries = valid
                }
            }
        }
    }

    private func persistAsync() {
        let snap = entries
        let path = historyFilePath
        Task.detached(priority: .background) {
            SyncAndLatchingService.writeAtomicJSON(snap, to: path)
        }
    }
}
